#!/usr/bin/env node
// Usage: npm run set-api-url -- https://speak.example.com
// Bakes the backend address into the app. Release builds must use https (Android blocks cleartext traffic in release).
const fs = require('fs')
const path = require('path')
const url = (process.argv[2] || '').replace(/\/$/, '')
if (!/^https?:\/\/[^\s/]+/.test(url)) {
  console.error('usage: npm run set-api-url -- https://your.domain')
  process.exit(2)
}
if (url.startsWith('http://') && !/^(http:\/\/(10\.0\.2\.2|localhost|127\.0\.0\.1|192\.168\.|10\.|172\.(1[6-9]|2\d|3[01])\.))/.test(url)) {
  console.error('Refusing a non-local http:// address: use https for anything reachable from the internet.')
  process.exit(2)
}
fs.writeFileSync(
  path.join(__dirname, '..', 'src', 'apiUrl.generated.ts'),
  `// Generated by scripts/set-api-url.js.\nexport const GENERATED_API_URL = '${url}'\n`,
)
console.log('API address set to', url)
