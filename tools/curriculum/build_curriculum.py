#!/usr/bin/env python3
"""
Builds the vocabulary and phrasal verb parts of the course from compact text files, so content can grow without hand-writing JSON.

  python tools/curriculum/build_curriculum.py          # merges the text files below into backend/src/main/resources/curriculum/*.json and prints a summary

Sources (one item per line, fields separated by |; lines starting with # are comments):

  words/level-N.txt    the first words of each level, with a conversation:
                       word|part of speech|meaning|example (must contain the word exactly)|A: line|B: line|synonyms|antonyms
  words/enrich.txt     Kannada, collocation and theme for words that were added with words/level-N.txt:
                       id|Kannada meaning|common usage|theme
  words/more-N.txt     more words for level N, each with everything a learner needs:
                       word|part of speech|simple meaning|Kannada meaning|example (must contain the word exactly)|common usage (collocation)|synonyms|theme|note (may be empty)
  phrasal/level-N.txt  the first phrasal verbs of each level, with conversation practice (16 fields, see the file header)
  phrasal/enrich.txt   id|Kannada|SEPARABLE, INSEPARABLE or NONE|common usage|theme|register|other meanings (meaning^Kannada^example;;...)
  phrasal/more-N.txt   more phrasal verbs for level N:
                       verb|meaning|Kannada|SEPARABLE, INSEPARABLE or NONE|common usage|theme|register|example 1|example 2|example 3 (may be empty)|other meanings|mistake (wrong>>right>>why, may be empty)
                       An example may mark the form of the verb it uses with [[double brackets]]: He [[gave up]] smoking. Without brackets the verb must appear exactly.

The script is safe to run again: an item that is already in the JSON (same word or verb) is skipped, never duplicated or overwritten. It stops with a
message if a line is malformed (wrong number of fields, example without the word, unknown theme, empty Kannada, a word that is also a phrasal verb, a
"mistake" equal to its correction), and the backend (Curriculum.java) and its tests validate the result again when it loads. Everything here is plain text
written by a person: nothing is generated by a model at run time. The Kannada has not been reviewed by a native speaker.
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent.parent / 'backend' / 'src' / 'main' / 'resources' / 'curriculum'

WORD_THEMES = {'everyday', 'education', 'workplace', 'emotions', 'communication', 'travel', 'relationships', 'health', 'technology', 'personality', 'academic', 'confusing'}
PHRASAL_THEMES = {'everyday', 'education', 'workplace', 'relationships', 'travel', 'conversation'}
REGISTERS = {'neutral', 'informal', 'formal'}
SEPARABLE = {'SEPARABLE', 'INSEPARABLE', 'NONE'}
POS = {'noun', 'verb', 'adjective', 'adverb', 'preposition'}

BUILD = {
    'verb': "Write a sentence using the verb '{w}'.",
    'noun': "Write a sentence with the word '{w}'.",
    'adjective': "Describe something or someone with the word '{w}'.",
    'adverb': "Write a sentence with the word '{w}'.",
}

NOTES = {
    'SEPARABLE': 'Separable: the object can go between the verb and the particle ({v}), and a pronoun (it, them, him, her) must go in the middle.',
    'INSEPARABLE': 'Not separable: the object always comes after the whole verb ({v}).',
    'NONE': 'No object is needed: it is used on its own ({v}), unless a preposition follows.',
}


def fail(msg):
    sys.exit(f'ERROR: {msg}')


def lines(path):
    for n, raw in enumerate(path.read_text(encoding='utf-8').splitlines(), 1):
        if raw.strip() and not raw.lstrip().startswith('#'):
            yield n, raw.rstrip('\n')


def write(path, header, key, items):
    body = ',\n'.join('    ' + json.dumps(i, ensure_ascii=False) for i in items)
    head = json.dumps(header, ensure_ascii=False)[1:-1]  # keeps level/title/summary on top
    path.write_text('{\n  ' + head.replace('", "', '",\n  "') + f',\n  "{key}": [\n{body}\n  ]\n}}\n', encoding='utf-8')


def load_all():
    words = {lvl: json.loads((OUT / f'vocabulary-{lvl}.json').read_text(encoding='utf-8')) for lvl in range(1, 6)}
    phrasal = {lvl: json.loads((OUT / f'phrasal-{lvl}.json').read_text(encoding='utf-8')) for lvl in range(1, 4)}
    return words, phrasal


def next_number(items, prefix, level):
    n = max([int(i['id'].split('.')[1]) for i in items] or [0]) + 1
    if n > 999:
        fail(f'level {level} is full (ids have at most three digits)')
    return f'{prefix}{level}.{n:02d}'


# ------------------------------------------------------------------------------------------------ vocabulary

def add_basic_words(words, level, taken):
    src = HERE / 'words' / f'level-{level}.txt'
    data = words[level]
    added = 0
    if not src.exists():
        return 0
    for n, raw in lines(src):
        f = raw.split('|')
        if len(f) != 8:
            fail(f'{src.name}:{n}: expected 8 fields, found {len(f)}')
        word, pos, meaning, example, a, b, syn, ant = [x.strip() for x in f]
        if word.lower() in taken:
            continue
        if not (a.startswith('A:') and b.startswith('B:')):
            fail(f'{src.name}:{n}: conversation lines must start with "A:" and "B:"')
        cloze, k = re.subn(r'\b' + re.escape(word) + r'\b', '___', example, count=1, flags=re.I)
        if not k:
            fail(f'{src.name}:{n}: the example sentence must contain "{word}" exactly')
        data['words'].append({
            'id': next_number(data['words'], 'v', level), 'word': word, 'pos': pos, 'meaning': meaning, 'example': example, 'conversation': [a, b],
            'synonyms': [s.strip() for s in syn.split(',') if s.strip()], 'antonyms': [s.strip() for s in ant.split(',') if s.strip()],
            'build': BUILD.get(pos, BUILD['noun']).format(w=word), 'cloze': cloze, 'answers': [word]})
        taken.add(word.lower())
        added += 1
    return added


def enrich_words(words):
    src = HERE / 'words' / 'enrich.txt'
    by_id = {w['id']: w for d in words.values() for w in d['words']}
    if src.exists():
        for n, raw in lines(src):
            f = [x.strip() for x in raw.split('|')]
            if len(f) != 4:
                fail(f'{src.name}:{n}: expected 4 fields, found {len(f)}')
            wid, kn, colloc, theme = f
            if wid not in by_id:
                fail(f'{src.name}:{n}: unknown word id {wid}')
            if not kn or not colloc:
                fail(f'{src.name}:{n}: Kannada and common usage are required')
            if theme not in WORD_THEMES:
                fail(f'{src.name}:{n}: unknown theme {theme}')
            w = by_id[wid]
            w['kn'], w['collocation'], w['theme'] = kn, colloc, theme
    missing = [i for i, w in by_id.items() if not (w.get('kn') and w.get('theme') and w.get('collocation'))]
    if missing:
        fail(f'words without Kannada, usage or theme (add them to words/enrich.txt): {", ".join(missing[:10])}')


def add_more_words(words, level, taken):
    src = HERE / 'words' / f'more-{level}.txt'
    data = words[level]
    added = 0
    if not src.exists():
        return 0
    for n, raw in lines(src):
        f = [x.strip() for x in raw.split('|')]
        if len(f) != 9:
            fail(f'{src.name}:{n}: expected 9 fields, found {len(f)}: {raw[:60]}')
        word, pos, meaning, kn, example, colloc, syn, theme, note = f
        if word.lower() in taken:
            continue
        if pos not in POS:
            fail(f'{src.name}:{n}: unknown part of speech "{pos}" for {word}')
        if theme not in WORD_THEMES:
            fail(f'{src.name}:{n}: unknown theme "{theme}" for {word}')
        if not (meaning and kn and colloc):
            fail(f'{src.name}:{n}: meaning, Kannada and common usage are required for {word}')
        if len(meaning) >= 130:
            fail(f'{src.name}:{n}: the meaning of {word} is too long to read at a glance')
        cloze, k = re.subn(r'\b' + re.escape(word) + r'\b', '___', example, count=1, flags=re.I)
        if not k:
            fail(f'{src.name}:{n}: the example sentence must contain "{word}" exactly')
        syns = [s.strip() for s in syn.split(',') if s.strip()]
        if word.lower() in [s.lower() for s in syns]:
            fail(f'{src.name}:{n}: {word} is its own synonym')
        item = {
            'id': next_number(data['words'], 'v', level), 'word': word, 'pos': pos, 'meaning': meaning, 'kn': kn, 'example': example, 'collocation': colloc,
            'theme': theme, 'synonyms': syns, 'antonyms': [], 'build': BUILD.get(pos, BUILD['noun']).format(w=word), 'cloze': cloze, 'answers': [word]}
        if note:
            item['note'] = note
        data['words'].append(item)
        taken.add(word.lower())
        added += 1
    return added


# ------------------------------------------------------------------------------------------------ phrasal verbs

def parse_senses(text, where):
    out = []
    for part in [p for p in text.split(';;') if p.strip()]:
        bits = [b.strip() for b in part.split('^')]
        if len(bits) != 3 or not all(bits):
            fail(f'{where}: other meanings must look like meaning^Kannada^example')
        out.append({'meaning': bits[0], 'kn': bits[1], 'example': bits[2]})
    return out


def enrich_phrasal(phrasal):
    src = HERE / 'phrasal' / 'enrich.txt'
    by_id = {l['id']: l for d in phrasal.values() for l in d['lessons']}
    if src.exists():
        for n, raw in lines(src):
            f = [x.strip() for x in raw.split('|')]
            if len(f) not in (6, 7):
                fail(f'{src.name}:{n}: expected 6 or 7 fields, found {len(f)}')
            lid, kn, sep, usage, theme, register = f[:6]
            extra = f[6] if len(f) == 7 else ''
            if lid not in by_id:
                fail(f'{src.name}:{n}: unknown phrasal verb id {lid}')
            if sep not in SEPARABLE or theme not in PHRASAL_THEMES or register not in REGISTERS or not kn or not usage:
                fail(f'{src.name}:{n}: separability, theme, register, Kannada and usage must all be valid')
            l = by_id[lid]
            l['kn'], l['separable'], l['usage'], l['theme'], l['register'] = kn, sep, usage, theme, register
            l['senses'] = [{'meaning': l['meaning'], 'kn': kn, 'example': l['examples'][0]}] + parse_senses(extra, f'{src.name}:{n}')
    missing = [i for i, l in by_id.items() if not (l.get('kn') and l.get('theme') and l.get('senses'))]
    if missing:
        fail(f'phrasal verbs without Kannada, theme or meanings (add them to phrasal/enrich.txt): {", ".join(missing[:10])}')


def mark(example, verb, where):
    """Returns (sentence without markup, the form of the verb used)."""
    m = re.search(r'\[\[(.+?)\]\]', example)
    if m:
        return example.replace('[[', '').replace(']]', ''), m.group(1)
    if not re.search(r'\b' + re.escape(verb) + r'\b', example, flags=re.I):
        fail(f'{where}: the example "{example}" must contain "{verb}" exactly, or mark the form used with [[double brackets]]')
    return example, verb


def blank(sentence, form, where):
    out, k = re.subn(r'\b' + re.escape(form) + r'\b', '___', sentence, count=1, flags=re.I)
    if not k:
        fail(f'{where}: could not blank "{form}" in "{sentence}"')
    return out


def add_more_phrasal(phrasal, level, taken):
    src = HERE / 'phrasal' / f'more-{level}.txt'
    data = phrasal[level]
    added = 0
    if not src.exists():
        return 0
    all_meanings = [l['meaning'] for d in phrasal.values() for l in d['lessons']]
    for n, raw in lines(src):
        where = f'{src.name}:{n}'
        f = [x.strip() for x in raw.split('|')]
        if len(f) != 12:
            fail(f'{where}: expected 12 fields, found {len(f)}: {raw[:60]}')
        verb, meaning, kn, sep, usage, theme, register, e1, e2, e3, extra, mistake = f
        if verb.lower() in taken:
            continue
        if sep not in SEPARABLE or theme not in PHRASAL_THEMES or register not in REGISTERS:
            fail(f'{where}: invalid separability, theme or register for {verb}')
        if not (meaning and kn and usage and e1 and e2):
            fail(f'{where}: meaning, Kannada, usage and two examples are required for {verb}')
        s1, form1 = mark(e1, verb, where)
        s2, form2 = mark(e2, verb, where)
        if s1 == s2:
            fail(f'{where}: the two examples of {verb} are the same')
        examples = [s1, s2]
        if e3:
            s3, _ = mark(e3, verb, where) if ('[[' in e3 or re.search(r'\b' + re.escape(verb) + r'\b', e3, flags=re.I)) else (e3, verb)
            examples.append(s3)
        mistakes = []
        if mistake:
            bits = [b.strip() for b in mistake.split('>>')]
            if len(bits) != 3 or bits[0].lower() == bits[1].lower():
                fail(f'{where}: the mistake must look like wrong>>right>>why, and differ from its correction')
            mistakes = [{'wrong': bits[0], 'right': bits[1], 'why': bits[2]}]
        senses = [{'meaning': meaning, 'kn': kn, 'example': s1}] + parse_senses(extra, where)
        cloze1, cloze2 = blank(s1, form1, where), blank(s2, form2, where)
        i = len(data['lessons'])
        others = [m for m in all_meanings if m != meaning]
        d1, d2 = others[(i * 7 + 3) % len(others)], others[(i * 7 + 11) % len(others)]
        if d1 == d2:
            d2 = others[(i * 7 + 12) % len(others)]
        pos1 = i % 3
        opts1 = [d1, d2]
        opts1.insert(pos1, meaning)
        questions = [
            {'type': 'choice', 'prompt': f"What does '{verb}' mean?", 'options': opts1, 'answer': pos1, 'why': f'{verb} = {meaning}.'},
            {'type': 'fill', 'prompt': f'{cloze1} ({verb})', 'answers': [form1], 'why': f"Use the phrasal verb '{verb}': {s1}"},
            {'type': 'fill', 'prompt': f'{cloze2} ({verb})', 'answers': [form2], 'why': f"Use the phrasal verb '{verb}': {s2}"}]
        if mistakes:
            pos3 = i % 2
            opts3 = [mistakes[0]['wrong']]
            opts3.insert(pos3, mistakes[0]['right'])
            questions.append({'type': 'choice', 'prompt': 'Choose the correct sentence.', 'options': opts3, 'answer': pos3, 'why': mistakes[0]['why']})
        item = {
            'id': next_number(data['lessons'], 'p', level), 'verb': verb, 'meaning': meaning, 'kn': kn, 'note': NOTES[sep].format(v=verb), 'separable': sep,
            'usage': usage, 'theme': theme, 'register': register, 'senses': senses, 'examples': examples, 'mistakes': mistakes, 'cloze': cloze1,
            'answers': [form1], 'assessment': questions}
        data['lessons'].append(item)
        taken.add(verb.lower())
        all_meanings.append(meaning)
        added += 1
    return added


# ------------------------------------------------------------------------------------------------ main

def main():
    words, phrasal = load_all()
    taken_words = {w['word'].lower() for d in words.values() for w in d['words']}
    taken_verbs = {l['verb'].lower() for d in phrasal.values() for l in d['lessons']}
    for lvl in range(1, 6):
        add_basic_words(words, lvl, taken_words)
    enrich_words(words)
    new_words = {lvl: add_more_words(words, lvl, taken_words) for lvl in range(1, 6)}
    for lvl in range(1, 4):
        # the existing basic phrasal files (16 fields) are handled by the earlier script revision; their lessons are already merged
        pass
    enrich_phrasal(phrasal)
    new_phrasal = {lvl: add_more_phrasal(phrasal, lvl, taken_verbs) for lvl in range(1, 4)}

    clash = taken_words & taken_verbs
    if clash:
        fail(f'a phrasal verb is also taught as a word: {sorted(clash)[:5]}')
    for lvl, d in words.items():
        write(OUT / f'vocabulary-{lvl}.json', {k: v for k, v in d.items() if k != 'words'}, 'words', d['words'])
    for lvl, d in phrasal.items():
        write(OUT / f'phrasal-{lvl}.json', {k: v for k, v in d.items() if k != 'lessons'}, 'lessons', d['lessons'])

    tw = sum(len(d['words']) for d in words.values())
    tp = sum(len(d['lessons']) for d in phrasal.values())
    ts = sum(len(l['senses']) for d in phrasal.values() for l in d['lessons'])
    for lvl in range(1, 6):
        print(f'vocabulary level {lvl}: +{new_words[lvl]} new, {len(words[lvl]["words"])} words')
    for lvl in range(1, 4):
        print(f'phrasal level {lvl}: +{new_phrasal[lvl]} new, {len(phrasal[lvl]["lessons"])} verbs')
    print(f'total: {tw} words, {tp} phrasal verbs ({ts} meanings)')


if __name__ == '__main__':
    main()
